export type ApiRoute = {
  readonly method: 'get' | 'post' | 'patch' | 'put' | 'delete';
  readonly path: string;
  readonly tag: string;
  readonly summary: string;
  /** True for the open routes; every other route requires the Bearer token through the gateway guards. */
  readonly isPublic?: boolean;
  readonly requestParams?: { readonly schema: z.ZodType; readonly name: string };
  readonly requestQuery?: z.ZodType;
  readonly requestBody?: {
    readonly schema: z.ZodType;
    readonly name: string;
    readonly mediaType?: 'application/json' | 'multipart/form-data';
  };
  readonly success: {
    readonly status: number;
    readonly name?: string;
    readonly schema?: z.ZodType;
    /** The photo bytes and the notification SSE stream are raw bodies, with no JSON schema. */
    readonly kind?: 'binary' | 'event-stream';
    readonly description: string;
  };
  /** HTTP statuses the gateway or a service can answer with, beside the shared ErrorResponse component. */
  readonly errors: ReadonlyArray<number>;
};

